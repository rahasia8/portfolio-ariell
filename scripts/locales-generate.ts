import { format, resolveConfig } from "prettier";
import { mkdir, readFile, readdir, rename, writeFile } from "node:fs/promises";
import path from "node:path";
import { generateTranslation } from "../lib/translate";
import { normalizeLanguage } from "../lib/locale";
import { validateTranslation, translations } from "../lib/translations";
const requested = process.argv.slice(2);
if (!requested.length) {
  console.error("Usage: npm run locales:generate -- fr es ja ...");
  process.exit(1);
}
const languages = requested.map((value) => {
  const language = normalizeLanguage(value);
  if (!language) throw new Error(`Invalid locale: ${value}`);
  return language;
});
await mkdir("locales/messages", { recursive: true });
async function saveAtomic(file: string, value: string) {
  const temporary = `${file}.${process.pid}.tmp`;
  await writeFile(
    temporary,
    await format(value, { ...(await resolveConfig(file)), filepath: file }),
  );
  await rename(temporary, file);
}
let failures = 0;
const queue = [...new Set(languages)];
async function worker() {
  while (queue.length) {
    const language = queue.shift()!;
    const file = path.join("locales/messages", `${language}.json`);
    try {
      validateTranslation(JSON.parse(await readFile(file, "utf8")));
      console.log(`${language}: existing catalog preserved`);
      continue;
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
    }
    try {
      let messages;
      for (let attempt = 0; attempt < 2; attempt++) {
        try {
          messages = await generateTranslation(language);
          if (
            language.split("-")[0] !== "en" &&
            messages.heading === translations.en.heading
          )
            throw new Error("Generated catalog still has the English heading");
          break;
        } catch (error) {
          if (attempt === 1) throw error;
        }
      }
      await saveAtomic(
        file,
        JSON.stringify(validateTranslation(messages), null, 2) + "\n",
      );
      console.log(`${language}: saved and validated`);
    } catch (error) {
      failures++;
      console.error(
        `${language}: ${error instanceof Error ? error.message : "generation failed"}`,
      );
    }
  }
}
await Promise.all([worker(), worker()]);
const files = (await readdir("locales/messages"))
  .filter((file) => /^[a-z]{2,3}(?:-[a-zA-Z]{2,8}){0,2}\.json$/.test(file))
  .sort();
for (const file of files)
  validateTranslation(
    JSON.parse(await readFile(path.join("locales/messages", file), "utf8")),
  );
const catalog = Object.fromEntries(
  files.map((file) => [file.slice(0, -5), `messages/${file}`]),
);
await saveAtomic("locales/catalog.json", JSON.stringify(catalog, null, 2) + "\n");
const imports = files
  .map(
    (file) =>
      `  ${JSON.stringify(file.slice(0, -5))}: () => import(${JSON.stringify(`./messages/${file}`)}).then(module => module.default),`,
  )
  .join("\n");
await saveAtomic(
  "locales/catalog.ts",
  `// Generated by npm run locales:generate. Locale content lives in JSON.\nexport const catalogLoaders: Record<string, () => Promise<unknown>> = {\n${imports}\n};\n`,
);
const sources = JSON.parse(await readFile("locales/sources.json", "utf8"));
for (const locale of Object.keys(catalog))
  if (!sources.catalogs[locale])
    sources.catalogs[locale] = {
      origin: "Machine-translated project UI with configured Gemini model",
      model: process.env.GENERATION_MODEL || "configured provider",
      review: "Structurally validated; native-language review recommended",
    };
await saveAtomic("locales/sources.json", JSON.stringify(sources, null, 2) + "\n");
console.log(`${files.length} saved catalogs registered; ${failures} failed.`);
if (failures) process.exitCode = 1;
